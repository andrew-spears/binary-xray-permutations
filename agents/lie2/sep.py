"""Part B: can a lattice (coset) condition or a convexity condition on mu separate the failing weights of F_4 / G_2?
Prints the index of the lattice generated by the differences of the weights rho + w rho (regular, dominant) and, for each
failing mu, whether mu - mu_0 lies in it (lattice test), and whether mu is a midpoint of two regular rho + w rho weights
(convexity test).   Usage: python3 sep.py TYPE rank"""
import sys, itertools
from rs import *
from math import gcd
T, n = sys.argv[1], int(sys.argv[2]); R = RS(T, n); rho = R.rho
P = {R.dom(tuple(a + b for a, b in zip(rho, v))) for v in R.orbit(rho)}
reg = sorted(m for m in R.below(tuple(2 * x for x in rho)) if min(m) >= 1)
good = [m for m in reg if m in P]; bad = [m for m in reg if m not in P]
top = tuple(2 * x for x in rho)
def hnf(vs):
    """row echelon basis (integer) of the lattice spanned by vs"""
    B = []
    vs = [list(v) for v in vs if any(v)]
    for c in range(n):
        col = [v for v in vs if v[c]]
        rest = [v for v in vs if not v[c]]
        while len(col) > 1:
            col.sort(key=lambda v: abs(v[c])); p = col[0]
            new = [p]
            for v in col[1:]:
                q = v[c] // p[c]; w = [a - q * b for a, b in zip(v, p)]
                (new if w[c] else rest).append(w)
            col = new
        if col: B.append(col[0])
        vs = [v for v in rest if any(v)]
    return B
def member(B, v):
    v = list(v)
    for b in B:
        c = next(i for i in range(n) if b[i])
        if v[c] % b[c]: return False
        q = v[c] // b[c]; v = [a - q * x for a, x in zip(v, b)]
    return not any(v)
D = [tuple(int(x) for x in R.coords(tuple(a - b for a, b in zip(top, m)))) for m in good]   # simple-root coordinates
B = hnf(D); idx = 1
for b in B: idx *= abs(next(x for x in b if x))
print(f"{T}{n}: {len(good)} regular PRV weights, {len(bad)} failing; lattice spanned by 2rho - mu (PRV) has index {idx if len(B) == n else 'infinite'} in the root lattice")
for m in bad:
    d = tuple(int(x) for x in R.coords(tuple(a - b for a, b in zip(top, m))))
    mid = [(a, b) for a, b in itertools.combinations(good, 2) if all(x + y == 2 * z for x, y, z in zip(a, b, m))]
    print("   failing", m, "in that lattice:", member(B, d), " midpoint of two PRV weights:", mid[:2])
